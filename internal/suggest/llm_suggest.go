package suggest

import (
	"context"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/philterd/philterscope/internal/ollama"
	"github.com/philterd/philterscope/pkg/model"
)

// LLMSuggester implements Suggester using an LLM.
type LLMSuggester struct {
	Client *ollama.Client
}

// NewLLMSuggester creates a new LLMSuggester.
func NewLLMSuggester(client *ollama.Client) *LLMSuggester {
	return &LLMSuggester{Client: client}
}

// Suggest returns recommendations generated by the LLM.
func (s *LLMSuggester) Suggest(result model.AuditResult) []model.Recommendation {
	ctx := context.Background()

	prompt := s.buildPrompt(result)
	response, err := s.Client.Generate(ctx, prompt)
	if err != nil {
		return []model.Recommendation{{
			ID:          recommendationID(model.KindAI, "AI_ERROR"),
			Kind:        model.KindAI,
			Entity:      "AI_ERROR",
			Description: fmt.Sprintf("Failed to generate AI recommendations: %v", err),
			Action:      "Check Ollama status and configuration.",
			IsAI:        true,
		}}
	}

	return s.parseResponse(response)
}

func (s *LLMSuggester) buildPrompt(result model.AuditResult) string {
	var sb strings.Builder
	sb.WriteString("You are a PII redaction policy expert. Based on the following audit result, suggest policy changes in Philter. ")
	sb.WriteString("Provide the suggestions in JSON format as an array of objects with fields: entity, description, action, snippet.\n\n")
	sb.WriteString(fmt.Sprintf("Audit Result: F1 Score: %.2f, Precision: %.2f, Recall: %.2f\n", result.F1Score, result.Precision, result.Recall))
	sb.WriteString("Entity Metrics:\n")
	for entity, recall := range result.EntityMetrics {
		sb.WriteString(fmt.Sprintf("- %s: Recall %.1f%%\n", entity, recall*100))
	}
	sb.WriteString("\nJSON Output Only:")
	return sb.String()
}

func (s *LLMSuggester) parseResponse(response string) []model.Recommendation {
	// Simple JSON extraction from the response
	start := strings.Index(response, "[")
	end := strings.LastIndex(response, "]")
	if start == -1 || end == -1 || start > end {
		return []model.Recommendation{{
			ID:          recommendationID(model.KindAI, "AI_PARSE_ERROR"),
			Kind:        model.KindAI,
			Entity:      "AI_PARSE_ERROR",
			Description: "Could not parse AI recommendations from response.",
			Action:      "Review AI output manually.",
			Snippet:     response,
			IsAI:        true,
		}}
	}

	var recs []model.Recommendation
	if err := json.Unmarshal([]byte(response[start:end+1]), &recs); err != nil {
		return []model.Recommendation{{
			ID:          recommendationID(model.KindAI, "AI_PARSE_ERROR"),
			Kind:        model.KindAI,
			Entity:      "AI_PARSE_ERROR",
			Description: fmt.Sprintf("Failed to decode AI recommendations: %v", err),
			Action:      "Review AI output manually.",
			Snippet:     response,
			IsAI:        true,
		}}
	}

	// An LLM can return several suggestions for one entity, and it supplies no
	// measurement, so the identity is the entity plus its position and the
	// structured evidence fields stay empty rather than being invented.
	for i := range recs {
		recs[i].IsAI = true
		recs[i].Kind = model.KindAI
		recs[i].ID = fmt.Sprintf("%s:%d", recommendationID(model.KindAI, recs[i].Entity), i)
		recs[i].Change = nil
		recs[i].Projection = &model.Projection{
			Predicted: false,
			Note:      "Generated by a language model from the audit summary, not computed from the detections. Verify it against the policy before applying it.",
		}
	}
	return recs
}
